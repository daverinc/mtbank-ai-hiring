def main():
    print("=== Генерация эталонных транскриптов ===\n")

    # 1. call_01_dialog.txt
    with open(f"{OUTPUT_DIR}/call_01_dialog.txt", "w", encoding="utf-8") as f:
        f.write(DIALOG_TRANSCRIPT)
    print("[1/5] Создан: call_01_dialog.txt")

    # 2. call_02_8khz.txt (тот же диалог)
    with open(f"{OUTPUT_DIR}/call_02_8khz.txt", "w", encoding="utf-8") as f:
        f.write(DIALOG_TRANSCRIPT)
    print("[2/5] Создан: call_02_8khz.txt")

    # 3–5. Монологи
    for i, (filename, text) in enumerate(MONOLOGUE_TRANSCRIPTS.items(), start=3):
        with open(f"{OUTPUT_DIR}/{filename}", "w", encoding="utf-8") as f:
            f.write(text)
        print(f"[{i}/5] Создан: {filename}")

    print("\n=== Все эталонные транскрипты успешно созданы ===")


if __name__ == "__main__":
    main()
